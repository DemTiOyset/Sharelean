package org.example.sharelane;

import org.openqa.selenium.By;
import org.openqa.selenium.WebDriver;
import org.openqa.selenium.WebElement;
import org.openqa.selenium.chrome.ChromeDriver;
import org.openqa.selenium.chrome.ChromeOptions;
import org.openqa.selenium.support.ui.ExpectedConditions;
import org.openqa.selenium.support.ui.Select;
import org.openqa.selenium.support.ui.WebDriverWait;
import org.testng.Assert;
import org.testng.annotations.AfterMethod;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.Test;

import java.time.Duration;

/**
 * End-to-end test for the ShareLane demo shop (https://sharelane.com).
 *
 * Covered flow:
 *   sign up (ZIP code step + account form) -> read generated credentials ->
 *   log in -> search a book -> add it to the shopping cart ->
 *   proceed to checkout -> try to pay and check the expected rejection.
 *
 * Run headless (default):
 *   mvn test
 * Run with a visible browser window:
 *   mvn test -Dheadless=false
 */
public class SharelaneE2ETest {

    private static final String BASE_URL = "https://sharelane.com/cgi-bin/";
    private static final String REGISTER_URL = BASE_URL + "register.py";
    private static final String LOGIN_URL = BASE_URL + "main.py";
    private static final String SHOPPING_CART_URL = BASE_URL + "shopping_cart.py";

    /** ShareLane accepts a 5-digit ZIP code on the sign up form. */
    private static final String VALID_ZIP_CODE = "12345";
    private static final String BOOK_KEYWORD = "War and Peace";
    private static final String BOOK_TITLE = "War and Peace";

    /** Dummy card number: ShareLane must reject it, real card data is never used. */
    private static final String DUMMY_CARD_NUMBER = "4242424242424242";

    private static final boolean HEADLESS = !"false".equalsIgnoreCase(System.getProperty("headless", "true"));
    private static final Duration TIMEOUT = Duration.ofSeconds(
            Integer.parseInt(System.getProperty("timeout.seconds", "30")));

    private WebDriver driver;
    private WebDriverWait wait;

    @BeforeMethod
    public void setUp() {
        ChromeOptions options = new ChromeOptions();
        if (HEADLESS) {
            options.addArguments("--headless=new");
        }
        options.addArguments(
                "--window-size=1920,1080",
                "--disable-gpu",
                "--no-sandbox",
                "--disable-dev-shm-usage");

        driver = new ChromeDriver(options);
        driver.manage().timeouts().pageLoadTimeout(TIMEOUT);
        wait = new WebDriverWait(driver, TIMEOUT);

        System.out.println("[setUp] Chrome started, headless=" + HEADLESS);
    }

    @AfterMethod(alwaysRun = true)
    public void tearDown() {
        if (driver != null) {
            driver.quit();
            System.out.println("[tearDown] Chrome closed");
        }
    }

    @Test(description = "Full ShareLane flow: sign up, log in, search, add to cart, checkout, payment rejection")
    public void shouldCompleteFullPurchaseFlow() {

        // ---------- 1. Sign up: ZIP code step ----------
        System.out.println("[step 1] Sign up: submitting ZIP code " + VALID_ZIP_CODE);
        driver.get(REGISTER_URL);

        WebElement zipCode = wait.until(ExpectedConditions.visibilityOfElementLocated(By.name("zip_code")));
        zipCode.sendKeys(VALID_ZIP_CODE);
        clickAndWaitForPageReload(By.cssSelector("input[value='Continue']"));

        // The account form is rendered only when the ZIP code passed the validation.
        WebElement firstName = wait.until(ExpectedConditions.visibilityOfElementLocated(By.name("first_name")));
        Assert.assertTrue(firstName.isDisplayed(),
                "Sign up form is not shown after a valid 5-digit ZIP code was submitted");

        // ---------- 2. Sign up: account form ----------
        String email = "umarov" + System.currentTimeMillis() + "@mail.com";
        String password = "TestPassword123";
        System.out.println("[step 2] Sign up: filling the account form with " + email);

        firstName.sendKeys("Timur");
        driver.findElement(By.name("last_name")).sendKeys("Umarov");
        driver.findElement(By.name("email")).sendKeys(email);
        driver.findElement(By.name("password1")).sendKeys(password);
        driver.findElement(By.name("password2")).sendKeys(password);
        clickAndWaitForPageReload(By.cssSelector("input[value='Register']"));

        WebElement body = driver.findElement(By.tagName("body"));
        Assert.assertTrue(body.getText().contains("Account is created!"),
                "Account was not created. Page text: " + body.getText());

        // ---------- 3. Read the credentials generated by ShareLane ----------
        String generatedEmail = readCredentialsCell("Email");
        String generatedPassword = readCredentialsCell("Password");
        System.out.println("[step 3] Generated credentials: " + generatedEmail + " / " + generatedPassword);

        Assert.assertTrue(generatedEmail.matches("[\\w.%+-]+@[\\w.-]+\\.sharelane\\.com"),
                "Generated e-mail has an unexpected format: " + generatedEmail);
        Assert.assertFalse(generatedPassword.isEmpty(), "Generated password is empty");

        // ---------- 4. Log in with the generated credentials ----------
        System.out.println("[step 4] Log in as " + generatedEmail);
        driver.get(LOGIN_URL);

        wait.until(ExpectedConditions.visibilityOfElementLocated(By.name("email"))).sendKeys(generatedEmail);
        driver.findElement(By.name("password")).sendKeys(generatedPassword);
        clickAndWaitForPageReload(By.cssSelector("input[value='Login']"));

        // ShareLane answers with a "Redirecting..." page and moves to main.py by JavaScript,
        // so here we wait for the greeting of the logged-in page, not just for a reload.
        wait.until(ExpectedConditions.textToBePresentInElementLocated(By.tagName("body"), "Hello"));

        WebElement keyword = wait.until(ExpectedConditions.visibilityOfElementLocated(By.name("keyword")));
        Assert.assertTrue(driver.getCurrentUrl().contains("main.py"),
                "Unexpected URL after login: " + driver.getCurrentUrl());

        WebElement loggedInBody = driver.findElement(By.tagName("body"));
        Assert.assertTrue(loggedInBody.getText().contains("Hello"),
                "Greeting is missing, the user looks not logged in. Page text: " + loggedInBody.getText());
        Assert.assertTrue(keyword.isDisplayed(), "Search field is not available after login");

        // ---------- 5. Search for a book ----------
        System.out.println("[step 5] Search for '" + BOOK_KEYWORD + "'");
        keyword.clear();
        keyword.sendKeys(BOOK_KEYWORD);
        clickAndWaitForPageReload(By.cssSelector("input[value='Search']"));

        Assert.assertTrue(driver.getPageSource().contains(BOOK_TITLE),
                "Search results do not contain '" + BOOK_TITLE + "'");

        WebElement addToCartLink = wait.until(
                ExpectedConditions.elementToBeClickable(By.cssSelector("a[href*='add_to_cart.py']")));
        Assert.assertTrue(addToCartLink.getAttribute("href").contains("book_id="),
                "Add to cart link does not point to a book: " + addToCartLink.getAttribute("href"));

        // ---------- 6. Add the book to the shopping cart ----------
        System.out.println("[step 6] Add the found book to the cart");
        addToCartLink.click();

        driver.get(SHOPPING_CART_URL);
        wait.until(ExpectedConditions.visibilityOfElementLocated(By.name("q")));
        String cartText = driver.findElement(By.tagName("body")).getText();

        Assert.assertTrue(cartText.contains(BOOK_TITLE),
                "Shopping cart does not contain '" + BOOK_TITLE + "'. Cart text: " + cartText);
        Assert.assertEquals(driver.findElement(By.name("q")).getAttribute("value"), "1",
                "Unexpected quantity of the book in the cart");

        // ---------- 7. Proceed to checkout ----------
        System.out.println("[step 7] Proceed to checkout");
        clickAndWaitForPageReload(By.cssSelector("input[value='Proceed to Checkout']"));

        WebElement cardNumber = wait.until(ExpectedConditions.visibilityOfElementLocated(
                By.cssSelector("input[name='card_number']:not([disabled])")));
        String checkoutText = driver.findElement(By.tagName("body")).getText();

        Assert.assertTrue(checkoutText.contains("Checkout"), "Checkout page is not opened");
        Assert.assertTrue(checkoutText.contains("Shipping"), "Shipping block is missing on the checkout page");
        Assert.assertTrue(checkoutText.contains(BOOK_TITLE),
                "Order details do not contain '" + BOOK_TITLE + "'. Checkout text: " + checkoutText);

        // ---------- 8. Payment: a dummy card must be rejected ----------
        System.out.println("[step 8] Try to pay with a dummy card (expected to be rejected)");
        new Select(driver.findElement(By.name("card_type_id"))).selectByValue("1");
        cardNumber.clear();
        cardNumber.sendKeys(DUMMY_CARD_NUMBER);
        clickAndWaitForPageReload(By.cssSelector("input[value='Make Payment']"));

        WebElement errorMessage = wait.until(
                ExpectedConditions.visibilityOfElementLocated(By.className("error_message")));
        System.out.println("[step 8] ShareLane response: " + errorMessage.getText());

        Assert.assertTrue(errorMessage.getText().contains("Invalid card number"),
                "Unexpected payment response: " + errorMessage.getText());
        Assert.assertTrue(errorMessage.isDisplayed(), "Payment error message is not visible");
    }

    /**
     * Reads a value from the "login info" table that ShareLane shows after a successful sign up.
     * The table looks like: <tr><td>Email</td><td>...</td></tr>
     */
    private String readCredentialsCell(String rowName) {
        WebElement cell = wait.until(ExpectedConditions.visibilityOfElementLocated(
                By.xpath("//td[normalize-space()='" + rowName + "']/following-sibling::td[1]")));
        return cell.getText().trim();
    }

    /**
     * Clicks an element that submits a form and waits until the browser really renders the next page.
     *
     * The old page stays in the DOM for a moment after the click. Without this wait the next check
     * runs against that old page: for example the search results assertion used to read the previous
     * page (the random book catalog) and failed even though ShareLane returned correct results.
     * Waiting for the old body to become stale removes that race.
     */
    private void clickAndWaitForPageReload(By locator) {
        WebElement previousBody = driver.findElement(By.tagName("body"));
        wait.until(ExpectedConditions.elementToBeClickable(locator)).click();
        wait.until(ExpectedConditions.stalenessOf(previousBody));
        wait.until(ExpectedConditions.visibilityOfElementLocated(By.tagName("body")));
    }
}
